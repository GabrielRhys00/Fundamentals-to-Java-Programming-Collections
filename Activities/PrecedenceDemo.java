public class PrecedenceDemo {

    public static void main(String[] args) {

        System.out.println(7 - 24 / 8 * 4 + 6);
        System.out.println((17 - 6 / 2) + 4 * 3);
        System.out.println(10 + 5 * 2);
        System.out.println((10 + 5) * 2);
        System.out.println(100 / 10 + 5);
        System.out.println(100 / (10 + 5));
    }
}
