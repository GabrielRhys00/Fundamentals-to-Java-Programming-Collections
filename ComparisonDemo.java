public class ComparisonDemo {

    public static void main(String[] args) {
        int a = 7;
        int b = 11;

        System.out.println("a = "+ a);
        System.out.println("b = "+ b);

        System.out.println("\na == b: " + (a == b));
        System.out.println("a != b: " + (a != b));
        System.out.println("a > b: " + (a > b));
        System.out.println("a < b: " + (a < b));
        System.out.println("a >= b: " + (a >= b));
        System.out.println("a <= b: " + (a <= b));
    }
}
